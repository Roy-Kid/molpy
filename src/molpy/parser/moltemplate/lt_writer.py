def _render_data_atoms(atomistic: Atomistic) -> list[str]:
    atoms = list(atomistic.atoms)
    if not atoms:
        return []
    names = _atom_name_map(atomistic)
    lines = ['  write("Data Atoms") {']
    for atom in atoms:
        aid = names[id(atom)]
        atype = atom["type"]
        charge = float(atom["charge"])
        x = float(atom["x"])
        y = float(atom["y"])
        z = float(atom["z"])
        lines.append(
            f"    $atom:{aid} $mol:. @atom:{atype} {_fmt(charge)} "
            f"{_fmt(x)} {_fmt(y)} {_fmt(z)}"
        )
    lines.append("  }")
    lines.append("")
    return lines


def _render_data_bonds(atomistic: Atomistic) -> list[str]:
    bonds = list(atomistic.bonds)
    if not bonds:
        return []
    names = _atom_name_map(atomistic)
    lines = ['  write("Data Bonds") {']
    for i, bond in enumerate(bonds, start=1):
        btype = bond.get("type") or "unknown"
        lines.append(
            f"    $bond:b{i} @bond:{btype} "
            f"$atom:{names[id(bond.itom)]} $atom:{names[id(bond.jtom)]}"
        )
    lines.append("  }")
    lines.append("")
    return lines


def _render_data_angles(atomistic: Atomistic) -> list[str]:
    angles = list(atomistic.angles)
    if not angles:
        return []
    names = _atom_name_map(atomistic)
    lines = ['  write("Data Angles") {']
    for i, ang in enumerate(angles, start=1):
        atype = ang.get("type") or "unknown"
        lines.append(
            f"    $angle:a{i} @angle:{atype} "
            f"$atom:{names[id(ang.itom)]} "
            f"$atom:{names[id(ang.jtom)]} "
            f"$atom:{names[id(ang.ktom)]}"
        )
    lines.append("  }")
    lines.append("")
    return lines


def _render_data_dihedrals(atomistic: Atomistic) -> list[str]:
    dihes = list(atomistic.dihedrals)
    if not dihes:
        return []
    names = _atom_name_map(atomistic)
    lines = ['  write("Data Dihedrals") {']
    for i, d in enumerate(dihes, start=1):
        dtype = d.get("type") or "unknown"
        lines.append(
            f"    $dihedral:d{i} @dihedral:{dtype} "
            f"$atom:{names[id(d.itom)]} "
            f"$atom:{names[id(d.jtom)]} "
            f"$atom:{names[id(d.ktom)]} "
            f"$atom:{names[id(d.ltom)]}"
        )
    lines.append("  }")
    lines.append("")
    return lines


def _render_data_impropers(atomistic: Atomistic) -> list[str]:
    imprs = list(atomistic.impropers)
    if not imprs:
        return []
    names = _atom_name_map(atomistic)
    lines = ['  write("Data Impropers") {']
    for i, d in enumerate(imprs, start=1):
        itype = d.get("type") or "unknown"
        lines.append(
            f"    $improper:i{i} @improper:{itype} "
            f"$atom:{names[id(d.itom)]} "
            f"$atom:{names[id(d.jtom)]} "
            f"$atom:{names[id(d.ktom)]} "
            f"$atom:{names[id(d.ltom)]}"
        )
    lines.append("  }")
    lines.append("")
    return lines


